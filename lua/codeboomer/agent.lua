-- [nfnl] fnl/codeboomer/agent.fnl
vim = vim
local review = require("codeboomer.review")
local M = {}
local shim_path = (vim.fn.stdpath("data") .. "/codeboomer-agent")
M["reply-instructions"] = function()
  return ("Reply to each thread above with: " .. shim_path .. " reply <thread-id> <text>\n")
end
local usage = "usage: codeboomer-agent reply <thread-id> <answer text>"
local function fail(msg)
  print(("codeboomer-agent: " .. msg .. "\n" .. usage))
  return os.exit(1, true)
end
M.main = function()
  local args = vim.split((os.getenv("CODEBOOMER_AGENT_ARGS") or ""), " ", {trimempty = true})
  local verb = args[1]
  if (verb ~= "reply") then
    return fail("expected 'reply' as the first argument")
  else
    local thread_id = tonumber(args[2])
    if not thread_id then
      return fail("thread id must be a number")
    else
      local body = table.concat(vim.list_slice(args, 3), " ")
      if (body == "") then
        return fail("missing answer text")
      else
        local id = review["agent-reply"](thread_id, body)
        if id then
          print(string.format("codeboomer-agent: posted reply to thread #%d (comment %d)", thread_id, id))
          return os.exit(0, true)
        else
          return fail("reply rejected")
        end
      end
    end
  end
end
local function shim_content()
  local entry
  do
    local t_5_ = vim.api.nvim_get_runtime_file("plugin/codeboomer.lua", false)
    if (nil ~= t_5_) then
      t_5_ = t_5_[1]
    else
    end
    entry = t_5_
  end
  if entry then
    local root = vim.fs.dirname(vim.fs.dirname(entry))
    local ld = (os.getenv("LD_LIBRARY_PATH") or "")
    return string.format("#!/usr/bin/env bash\n# codeboomer-agent \226\128\148 post review replies from outside nvim.\n# GENERATED by codeboomer.nvim on load \226\128\148 edits are overwritten.\nset -euo pipefail\nexport CODEBOOMER_PATH='%s'\nexport LD_LIBRARY_PATH='%s'\nexport CODEBOOMER_AGENT_ARGS=\"$*\"\nexec nvim --headless -u NONE --cmd \"set rtp^=${CODEBOOMER_PATH}\" -c 'lua require(\"codeboomer.agent\").main()' -c 'qa!'\n", root, ld)
  else
    return nil
  end
end
M["ensure-shim"] = function()
  local content = shim_content()
  if content then
    local lines = vim.split(content, "\n", {plain = true})
    local ok, existing = pcall(vim.fn.readfile, shim_path)
    local same = (ok and (type(existing) == "table") and (table.concat((existing or {}), "\n") == table.concat(lines, "\n")))
    if not same then
      vim.fn.writefile(lines, shim_path)
      return pcall(vim.loop.fs_chmod, shim_path, 493)
    else
      return nil
    end
  else
    return nil
  end
end
M["ensure-shim"]()
return M
